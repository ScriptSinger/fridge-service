import IMask from "imask";

export default (el) => {
    const mask = IMask(el, {
        mask: "+{7} (000) 000-00-00",
        lazy: false, // ← показывает маску сразу
    });

    // IMask меняет el.value программно и не порождает нативное событие
    // "input", поэтому x-model (который слушает el раньше, чем эта
    // директива успевает навесить маску) может остаться со старым,
    // ещё не отформатированным значением. Досылаем "input" вручную,
    // чтобы Alpine всегда видел итоговое замаскированное значение.
    // Диспатч откладываем в микротаску: если вызвать его синхронно
    // прямо из "accept", IMask ещё не вышел из обработки исходного
    // события и перехватывает наше синтетическое "input" как новый
    // ввод, из-за чего значение дублируется/портится.
    mask.on("accept", () => {
        queueMicrotask(() => {
            el.dispatchEvent(new Event("input", { bubbles: true }));
        });
    });
};
